import { createClient } from '@supabase/supabase-js';

const SUPABASE_URL = process.env.VITE_SUPABASE_URL;
const SUPABASE_ANON_KEY = process.env.VITE_SUPABASE_PUBLISHABLE_KEY;
const SUPABASE_SECRET_KEY = process.env.SUPABASE_SECRET_KEY;
if (!SUPABASE_URL || !SUPABASE_ANON_KEY || !SUPABASE_SECRET_KEY) {
  throw new Error('Missing required Supabase environment variables: VITE_SUPABASE_URL, VITE_SUPABASE_PUBLISHABLE_KEY, SUPABASE_SECRET_KEY');
}

export async function handleAIChatRequest(token: string, body: { prompt: string }): Promise<{ status: number; body: any }> {
  if (!token) {
    return { status: 401, body: { error: 'Authentication required. Please log in as a student.', code: 'UNAUTHORIZED' } };
  }

  // 1. Verify caller user identity
  const userClient = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
    auth: { persistSession: false },
    global: { headers: { Authorization: `Bearer ${token}` } }
  });

  const { data: { user: callerUser }, error: callerError } = await userClient.auth.getUser();
  if (callerError || !callerUser) {
    return { status: 401, body: { error: 'Invalid or expired session. Please log in again.', code: 'SESSION_EXPIRED' } };
  }

  const prompt = body?.prompt?.trim();
  if (!prompt) {
    return { status: 400, body: { error: 'Prompt is required.', code: 'VALIDATION_ERROR' } };
  }

  const supabaseAdmin = createClient(SUPABASE_URL, SUPABASE_SECRET_KEY, {
    auth: { autoRefreshToken: false, persistSession: false }
  });

  // 2. Persist student's user message to database
  await supabaseAdmin.from('ai_chat_messages').insert({
    user_id: callerUser.id,
    role: 'user',
    content: prompt,
    created_at: new Date().toISOString()
  });

  // 3. Check for real AI Provider API credentials
  const geminiApiKey = process.env.GEMINI_API_KEY || process.env.VITE_GEMINI_API_KEY;
  const openaiApiKey = process.env.OPENAI_API_KEY;

  if (!geminiApiKey && !openaiApiKey) {
    const errorMsg = 'AI Provider credentials (GEMINI_API_KEY or OPENAI_API_KEY) are not configured in environment variables. Please provide an API key in your .env file or Supabase Edge secrets to enable live responses.';
    
    // Persist system notice
    await supabaseAdmin.from('ai_chat_messages').insert({
      user_id: callerUser.id,
      role: 'ai',
      content: `⚠️ [Configuration Required] ${errorMsg}`,
      created_at: new Date().toISOString()
    });

    return {
      status: 503,
      body: {
        error: errorMsg,
        code: 'AI_PROVIDER_NOT_CONFIGURED',
        setup_required: 'Set GEMINI_API_KEY or OPENAI_API_KEY in .env file.'
      }
    };
  }

  // 4. Call Real AI Provider
  let generatedAnswer = '';

  try {
    if (geminiApiKey) {
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiApiKey}`;
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{
            parts: [{
              text: `You are an academic learning mentor at Adhithyan College. Answer this student's inquiry thoroughly, accurately, and step-by-step:\n\n${prompt}`
            }]
          }]
        })
      });

      if (!response.ok) {
        const errText = await response.text();
        throw new Error(`Gemini API error (${response.status}): ${errText}`);
      }

      const resJson = await response.json();
      generatedAnswer = resJson.candidates?.[0]?.content?.parts?.[0]?.text || 'No response generated by AI model.';
    } else if (openaiApiKey) {
      const endpoint = 'https://api.openai.com/v1/chat/completions';
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${openaiApiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-4o-mini',
          messages: [
            { role: 'system', content: 'You are an academic learning mentor at Adhithyan College. Answer the student inquiry thoroughly, accurately, and step-by-step.' },
            { role: 'user', content: prompt }
          ]
        })
      });

      if (!response.ok) {
        const errText = await response.text();
        throw new Error(`OpenAI API error (${response.status}): ${errText}`);
      }

      const resJson = await response.json();
      generatedAnswer = resJson.choices?.[0]?.message?.content || 'No response generated by AI model.';
    }

    // Persist real AI reply to database
    await supabaseAdmin.from('ai_chat_messages').insert({
      user_id: callerUser.id,
      role: 'ai',
      content: generatedAnswer,
      created_at: new Date().toISOString()
    });

    return {
      status: 200,
      body: {
        success: true,
        reply: generatedAnswer
      }
    };
  } catch (apiErr: any) {
    console.error('AI provider generation error:', apiErr);
    return {
      status: 502,
      body: {
        error: `Failed to generate response from AI provider: ${apiErr.message}`,
        code: 'AI_SERVICE_ERROR'
      }
    };
  }
}

